let ACTIVE_LANGUAGE = 'en';
const I18N_PREFS_KEY = 'sp_prefs_v1';

function normalizeLanguage(code) {
  const value = String(code || '').toLowerCase().split('-')[0];
  return UI_LANGUAGES.some((item) => item.code === value) ? value : 'en';
}
function getLanguage() { return ACTIVE_LANGUAGE; }
function getLanguageInfo(code) {
  const lang = normalizeLanguage(code || ACTIVE_LANGUAGE);
  return UI_LANGUAGES.find((item) => item.code === lang) || UI_LANGUAGES[0];
}
function getLocale() { return getLanguageInfo(ACTIVE_LANGUAGE).locale; }
function t(key, params) {
  const values = params || {};
  let text = (I18N[ACTIVE_LANGUAGE] && I18N[ACTIVE_LANGUAGE][key]) || I18N.en[key] || key;
  return String(text).replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) =>
    values[name] == null ? match : String(values[name]));
}
function tPlural(key, count) {
  let category = 'other';
  try { category = new Intl.PluralRules(getLocale()).select(Number(count)); } catch (e) { /* old WebView */ }
  const exact = I18N[ACTIVE_LANGUAGE] && I18N[ACTIVE_LANGUAGE][key + '.' + category];
  const fallback = I18N[ACTIVE_LANGUAGE] && I18N[ACTIVE_LANGUAGE][key + '.other'];
  const value = exact || fallback || I18N.en[key + '.other'] || key;
  return String(value).replace(/\{count\}/g, String(count));
}
function applyI18n(root) {
  if (typeof document === 'undefined') return;
  const scope = root || document;
  const selectors = '[data-i18n], [data-i18n-html], [data-i18n-title], ' +
    '[data-i18n-aria-label], [data-i18n-placeholder], [data-i18n-content], [data-i18n-alt]';
  const nodes = [];
  if (scope.matches && scope.matches(selectors)) nodes.push(scope);
  if (scope.querySelectorAll) nodes.push(...scope.querySelectorAll(selectors));
  for (const el of nodes) {
    let params = {};
    try { params = el.dataset.i18nParams ? JSON.parse(el.dataset.i18nParams) : {}; } catch (e) {}
    if (el.dataset.i18n) el.textContent = t(el.dataset.i18n, params);
    if (el.dataset.i18nHtml) el.innerHTML = t(el.dataset.i18nHtml, params);
    if (el.dataset.i18nTitle) el.setAttribute('title', t(el.dataset.i18nTitle));
    if (el.dataset.i18nAriaLabel) el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
    if (el.dataset.i18nPlaceholder) el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
    if (el.dataset.i18nContent) el.setAttribute('content', t(el.dataset.i18nContent));
    if (el.dataset.i18nAlt) el.setAttribute('alt', t(el.dataset.i18nAlt));
  }
}
function setLanguage(code) {
  ACTIVE_LANGUAGE = normalizeLanguage(code);
  if (typeof document !== 'undefined' && document.documentElement) {
    const info = getLanguageInfo(ACTIVE_LANGUAGE);
    document.documentElement.lang = info.code;
    document.documentElement.dir = info.dir;
    applyI18n(document);
  }
  return ACTIVE_LANGUAGE;
}

/* Restore the saved choice before the app boots. No browser-language guessing:
   first launch always starts in English, as requested. */
try {
  const savedPrefs = JSON.parse(localStorage.getItem(I18N_PREFS_KEY) || '{}');
  ACTIVE_LANGUAGE = normalizeLanguage(savedPrefs && savedPrefs.language || 'en');
} catch (e) { ACTIVE_LANGUAGE = 'en'; }
setLanguage(ACTIVE_LANGUAGE);
